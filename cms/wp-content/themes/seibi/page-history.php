            <p>
              サレジアン・シスターズ（扶助者聖母会）の創立者は、聖ドン・ボスコ（聖ヨハネ・ボスコ）です。<br />
              聖ドン・ボスコは、1815年8月16日北イタリア・トリノ市近くのベッキという農村に生まれました。<br />
              ドン・ボスコが育った時代は、イタリア統一運動によって教会と政府の関係が大きく揺れ動き産業革命の波によって社会全体に大きな変革をもたらし、若者たちは教育どころか劣悪な環境の中で過酷な労働を強いられました。
              ドン・ボスコは、この状況から若者を救い誠実な社会人に教育し自立させるために教育修道会であるサレジオ会を創立しました。キリスト教の教えに基づいた「予防教育法」という独自の教育法を実践し今も世界中に広がる会員によって若者の心の叫びに答えています。<br />
              その事業が盛んになるにつれ、同じ教育を女子にも行うようにと教会やその他から要請され「サレジアン・シスターズ」（扶助者聖母会）を創立しました。
            </p>
            <p><small>「サレジアン・シスターズ」の創立にあたり聖ドン・ボスコは、「聖マリア・マザレロ」を共創立者として起用しました。</small></p>
          </div>
          <div class="col-lg-6 col-12">
