            <p>
              聖マリア・マザレロは、北イタリア、アレキサンドリア州の小村モルネーゼで、１８３７年に生まれました。<br />
              信仰深い両親のもとで成長し、当時のモルネーゼの教会の助任司祭ペスタリーノ神父から多くの薫陶を受けていました。<br />
              聖ドン・ボスコと助任司祭ペスタリーノ神父との摂理的な出会いを通して神は、聖マリア・マザレロに同じ聖霊の働きによる女子のため教育活動に参与するように、計らわれたのでありました。<br />
              このマリア・マザレロのグループを基礎として１８７２年、聖ドン・ボスコの「サレジオ会」と並ぶ女子修道会を創立し、扶助者である聖母マリアへの感謝の生きた記念碑として「扶助者聖母会」と名付けました。
            </p>
            <p>
              <small
                >星美学園は、このサレジアン・シスターズを母体とし、世界91ヶ国1500余支部を有する国際的カトリックミッションスクールです。<br />
                日本においては、東京、静岡、大阪、大分に幼稚園を６園、小学校を４校、中高を４校、短大を１校の教育施設と、福祉施設２つを有します。</small
